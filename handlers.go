package main

import (
    "encoding/json"
    "os"
    "log"
    "net/http"
    "fmt"
)


func LoadNews(filename string) (*AutoGenerated, error) {
    data, err := os.ReadFile(filename)
    if err != nil {
        return nil, err
    }

    var news AutoGenerated
    fmt.Println(news)
    //  json.Unmarshal для десериализации
    if err := json.Unmarshal(data, &news); err != nil {
        return nil, err
    }
    fmt.Println(news)
    return &news, nil
}


func indexHandler(w http.ResponseWriter, r *http.Request) {
    news, err := LoadNews("news.json")
    if err != nil {
        log.Printf("Failed to load news: %v", err)
        http.Error(w, "Failed to load news",
            http.StatusInternalServerError)
        return
    }

    if err := tpl.Execute(w, news); err != nil {
        log.Printf("Failed to render template: %v", err)
    }

}